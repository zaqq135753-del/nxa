import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/services/activationModel.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const model = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const draft = model.emptyActivation('draft');
assert.equal(model.activationErrors(draft, 0).length, 2);
assert.equal(model.parseActivation({ ...draft, niche: '__proto__', step: 200 }, 'draft').niche, 'restaurante');
assert.equal(model.parseActivation({ ...draft, step: 200 }, 'draft').step, 3);
assert.equal(model.parseActivation({ ...draft, id: 'foreign' }, 'draft').name, '');
assert.equal(model.safeActivationImage('javascript:alert(1)'), undefined);
assert.equal(model.safeActivationImage('data:image/svg+xml;base64,AAAA'), undefined);
assert.equal(model.safeActivationImage('https://example.com/facade.jpg'), 'https://example.com/facade.jpg');
assert.equal(model.activationErrors({ ...draft, latitude: '91', longitude: '0', reference: 'Vila' }, 1).length, 1);
assert.equal(model.activationErrors({ ...draft, latitude: '', longitude: '0', reference: 'Vila' }, 1).length, 1);
assert.match(model.niches.pousada.action, /reservas/);
assert.doesNotMatch(model.niches.pousada.action, /TapTable/);
assert.equal(Object.keys(model.niches).length, 8);
console.log('12 verificações do modelo de ativação aprovadas.');
